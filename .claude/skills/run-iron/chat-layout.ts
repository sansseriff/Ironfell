import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
const dpr = Number(process.env.DPR ?? 1);
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1680, height: 1000 }, deviceScaleFactor: dpr });
const errors: string[] = [];
page.on('pageerror', error => errors.push(String(error)));
try {
  await page.goto(process.env.URL ?? 'http://localhost:5189/Ironfell/?gfx=webgl2&demo');
  page.setDefaultTimeout(15000);
  await page.getByRole('button', { name: 'lesson', exact: true }).first().click();
  await page.waitForFunction(() => (window as any).__narrative?.get('lesson')?.status().blocks > 1, undefined, { timeout: 15000 });
  const narrative = page.locator('.narrative').first();
  await narrative.locator('[data-mode-button="hybrid"]').click();
  const divider = narrative.getByRole('separator');
  const chat = narrative.locator('.conversation-host');
  const initial = (await chat.boundingBox())!;
  const handle = (await divider.boundingBox())!;
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2, handle.y - 100, { steps: 10 });
  await page.mouse.up();
  assert.ok((await chat.boundingBox())!.height > initial.height + 70, 'dragging up enlarges history');
  await divider.focus();
  await page.keyboard.press('ArrowDown');
  const adjusted = Number(await divider.getAttribute('aria-valuenow'));
  await page.keyboard.press('Home');
  assert.equal(await divider.getAttribute('aria-valuenow'), '18');
  await page.keyboard.press('End');
  assert.equal(await divider.getAttribute('aria-valuenow'), '78');
  await page.keyboard.press('Enter');
  assert.equal(await divider.getAttribute('aria-valuenow'), '60');
  assert.ok(adjusted < 60);
  await mkdir(`.agents/chat-layout/dpr${dpr}`, { recursive: true });
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme });
    await page.screenshot({ path: `.agents/chat-layout/dpr${dpr}/hybrid-${theme}.png` });
    await narrative.locator('[data-mode-button="authoring"]').click();
    const composer = narrative.locator('.composer');
    assert.equal(await composer.evaluate(el => getComputedStyle(el).paddingBottom), '20px');
    assert.equal(await narrative.locator('.chat-threads').evaluate(el => getComputedStyle(el).borderBottomWidth), '0px');
    await page.screenshot({ path: `.agents/chat-layout/dpr${dpr}/authoring-${theme}.png` });
    await narrative.locator('[data-mode-button="hybrid"]').click();
    assert.equal(await divider.getAttribute('aria-valuenow'), '60', 'mode changes preserve split');
  }
  const settings = page.getByRole('button', { name: 'Settings', exact: true });
  assert.equal((await settings.boundingBox())!.width, 32);
  await settings.hover();
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await settings.click();
  await page.getByRole('dialog', { name: 'Settings', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name: 'Settings', exact: true }).waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 1100, height: 700 });
  const small = (await chat.boundingBox())!;
  assert.ok(small.height > 100);
  assert.deepEqual(errors, []);
  console.log(`PASS chat layout DPR ${dpr}: drag, keyboard bounds/reset, mode switching, compact spacing, light/dark; no page errors`);
} finally { await browser.close(); }
