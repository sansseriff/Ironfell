#!/usr/bin/env python3
"""Generate TS wire types from the shared Rust request enum and command table.
No parallel command registry: field names/types come from engine_api signatures.
The deliberately small Rust grammar fails closed when a new type needs support.
"""
from pathlib import Path
import re, sys
root = Path(__file__).resolve().parents[1]
def read(name): return (root / name).read_text()
def ts_type(t):
    t=t.strip()
    if t in ['String', '&str']: return 'string'
    if t == 'bool': return 'boolean'
    if t in ['u8','u32','u64','i64','f32','f64','usize']: return 'number'
    if t in ['Value', 'serde_json::Value']: return 'unknown'
    if t == 'FontRequest': return '{ family: string; file: string }'
    if re.fullmatch(r'\[f32;\s*3\]',t): return '[number, number, number]'
    if t.startswith('Option<'): return ts_type(t[7:-1])+' | null'
    if t.startswith('Vec<'): return '('+ts_type(t[4:-1])+')[]'
    raise ValueError('Unsupported protocol type: '+t)
api=read('src/engine_api.rs'); dispatch=read('src/engine_dispatch.rs')
commands=[]
for name, body in re.findall(r'^        "(\w+)"\s*=>\s*\{(.*?)\}\s*,?', dispatch, re.M | re.S):
    target=re.search(r'crate::engine_api::(\w+)\(',body).group(1)
    signature=re.search(r'pub fn '+target+r'\((.*?)\)\s*(?:->|\{)', api, re.S).group(1)
    fields=[]
    for field in signature.split(','):
        if not field.strip(): continue
        key,typ=field.strip().split(':',1)
        if 'WorkerApp' in typ: continue
        fields.append((key.strip(),ts_type(typ)))
    arity=int(re.search(r'arity\(\s*args,\s*(\d+)\s*\)',body).group(1))
    arguments=re.findall(r'argument::<(.*?)>\(\s*args,\s*(\d+)\s*\)',body)
    assert arity == len(fields), (name, 'signature/arity mismatch')
    assert [int(index) for _,index in arguments] == list(range(arity)), (name, 'non-positional argument order')
    assert [ts_type(typ) for typ,_ in arguments] == [typ for _,typ in fields], (name, 'signature/argument type mismatch')
    commands.append((name,fields))
assert len(commands) == len(re.findall(r'^        "\w+" =>',dispatch,re.M))
out=['// Generated by scripts/generate-ui-protocol.py. Do not edit.','export type DocumentCommand =']
for name,fields in commands:
    out.append('  | { op: '+repr(name)+''.join('; '+key+': '+typ for key,typ in fields)+' }')
out += [';', '', 'export function documentArguments(command: DocumentCommand): { fn: string; args: unknown[] } {','  switch (command.op) {']
for name,fields in commands:
    out.append('    case '+repr(name)+': return { fn: command.op, args: ['+', '.join('command.'+key for key,_ in fields)+'] };')
out += ['  }','}', '', 'export type EngineRequest =']
source=read('src/engine_protocol.rs').split('pub enum Request {',1)[1].split('\n}\n',1)[0]
variants=re.findall(r'^    (\w+)(?: \{([^{}]*)\})?,',source,re.M|re.S)
assert len(variants) == len(re.findall(r'^    (\w+)\b',source,re.M)), 'Unsupported request variant syntax'
for variant,body in variants:
    # Match normal multiline variants and unit variants; serde wire spelling is camelCase.
    tag=variant[0].lower()+variant[1:]
    fields=[]
    for rename,key,typ in re.findall(r'(?:#\[serde\(rename = "([^"]+)"\)\]\s*)?((?:r#)?\w+): ([^,\n]+),',body):
        key=rename or key.replace('r#','')
        fields.append('; '+key+('?' if typ.startswith('Option<') else '')+': '+ts_type(typ))
    out.append('  | { ty: '+repr(tag)+''.join(fields)+' }')
out += [';', '', 'export type EngineEvent =']
events=read('src/host_events.rs').split('pub enum EngineEvent {',1)[1].split('\n}\n',1)[0]
variants=re.findall(r'^    (\w+)(?: \{([^{}]*)\})?,',events,re.M)
assert len(variants) == len(re.findall(r'^    (\w+)\b',events,re.M)), 'Unsupported event variant syntax'
for variant,body in variants:
    tag=variant[0].lower()+variant[1:]
    fields=[]
    for key,typ in re.findall(r'(\w+): ([^,\n]+)',body):
        key=re.sub(r'_([a-z])',lambda m:m[1].upper(),key) if variant == 'StateChanged' else key
        fields.append('; '+key+': '+ts_type(typ))
    out.append('  | { ty: '+repr(tag)+''.join(fields)+' }')
out += [';', '']
text='\n'.join(out)
file=root/'src-ui/runtime/protocol.generated.ts'
if '--check' in sys.argv:
    if not file.exists() or file.read_text()!=text: sys.exit('Protocol types are stale; run bun run protocol')
else: file.write_text(text)
